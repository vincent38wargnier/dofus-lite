// Isolated browser data: this never opens or changes the player's browser saves.
require('./ai_runtime.cjs');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const puppeteer = require('puppeteer-core');
const { emptyLoadout } = require('../src/engine/equipment');
const out = process.env.PROOF_DIR || '/tmp/dofus-unified-combat';
const profile = { id: 'iop', name: 'Iop de première ligne', classId: 'IOP', className: 'Iop',
  loadout: { ...emptyLoadout('IOP'), level: 200, base: { force: 200 }, slots: { weapon: 2416 } } };
const room = { id: 'unified-room', name: 'Le refuge des Poutchs', mapId: 'dungeon_2083', members: [{ monsterId: 494, grade: 1, count: 2 }] };
(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, pipe: true });
  const page = await browser.newPage(), report = { errors: [], checks: [] };
  page.setDefaultTimeout(30000);
  page.on('pageerror', error => report.errors.push(error.message));
  const click = async (selector, text = '') => {
    const handle = await page.evaluateHandle(({ selector, text }) => [...document.querySelectorAll(selector)].find(e => e.checkVisibility() && e.textContent.includes(text)), { selector, text });
    assert(handle.asElement(), `Missing ${selector}: ${text}`); await handle.asElement().click(); await handle.dispose();
  };
  const visible = selector => page.$$eval(selector, nodes => nodes.some(node => node.checkVisibility()));
  const capture = async name => { await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: path.join(out, `${name}.png`) }); };
  const check = text => { report.checks.push(text); console.log(text); };
  const frameIndex = () => page.$eval('[data-auto-dungeon]', element => element.dataset.replayFrame);
  const stored = () => page.evaluate(() => localStorage.getItem('dofus-lite-player-setup-v1'));
  try {
    await page.setViewport({ width: 1440, height: 960 });
    await page.evaluateOnNewDocument(({ profile, room }) => {
      if (localStorage.getItem('unified-proof')) return;
      localStorage.setItem('unified-proof', '1');
      localStorage.setItem('dofus-lite-profiles-v1', JSON.stringify({ version: 1, activeId: profile.id, profiles: [profile] }));
      localStorage.setItem('dofus-lite-opponent-team-v1', JSON.stringify({ version: 1, entries: [{ kind: 'monster', monsterId: 494, grade: 1 }] }));
      localStorage.setItem('dofus-lite-creations-v1', JSON.stringify({ version: 1, characters: [], dungeons: [room] }));
      localStorage.setItem('dofus-lite-player-setup-v1', JSON.stringify({ mode: 'boss', customDungeonId: room.id, mapId: 'canyon', controller: 'ai', botId: 'pantin', playerBotId: 'maison' }));
      localStorage.setItem('dofus-lite-sound', JSON.stringify({ enabled: false, volume: 0 }));
    }, { profile, room });
    await page.goto(process.env.PROOF_URL || 'http://127.0.0.1:3013', { waitUntil: 'networkidle0' });
    assert.deepEqual(await page.$$eval('.tabs > button', nodes => nodes.map(node => node.textContent.trim())), ['Jouer', 'Atelier', 'Grimoire']);
    await click('.setup-navigation [aria-label="Combat"]');
    assert(await visible('.combat-inline'));
    assert.equal(await page.$eval('.combat-control-toggle button:last-child', e => e.getAttribute('aria-pressed')), 'true');
    await capture('combat-desktop');
    const before = await stored();
    await click('.combat-choice-launch');
    await page.waitForSelector('[data-auto-dungeon]', { timeout: 120000 });
    if (await visible('[aria-label="Pause"]')) await click('[aria-label="Pause"]');
    assert.equal(await page.$eval('.tabs > button:first-child', e => e.getAttribute('aria-current')), 'page');
    assert(!await visible('.arena-setup'));
    await click('.auto-result-button');
    assert.equal(await page.$eval('[data-outcome]', e => e.dataset.outcome), 'victory');
    const finalFrame = await frameIndex();
    await capture('result-desktop');
    check('Combat launches an automatic dungeon and shows the result under Jouer, without the old Arena setup');
    await click('.fight-heading-actions button', 'Retour à Combat');
    await click('.tabs > button', 'Atelier'); await click('.tabs > button', 'Jouer');
    assert(await visible('.combat-resume'));
    await capture('resume-desktop');
    await page.setViewport({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await capture('resume-mobile');
    await click('.combat-resume button');
    assert.equal(await frameIndex(), finalFrame);
    await page.setViewport({ width: 1440, height: 960 });
    await click('[aria-label="Revenir au début"]');
    assert.equal(await frameIndex(), '0');
    await click('[aria-label="Action suivante"]'); assert.equal(await frameIndex(), '1');
    await click('[aria-label="Revenir au début"]');
    await page.select('[aria-label="Vitesse de lecture"]', '4');
    await click('[aria-label="Lire le combat"]');
    await page.waitForFunction(() => Number(document.querySelector('[data-auto-dungeon]')?.dataset.replayFrame) > 0);
    if (await visible('[aria-label="Pause"]')) await click('[aria-label="Pause"]');
    await click('.fight-heading-actions button', 'Retour à Combat');
    assert(await visible('.combat-inline'));
    await click('.combat-resume button');
    await click('.fight-heading-actions button', 'Retour à Combat');
    assert(await visible('.combat-inline')); assert(await visible('.combat-resume'));
    assert.equal(await stored(), before);
    check('replay can be resumed after navigation on mobile; playback, speed and return preserve the setup');
    await click('.combat-choice-modes [data-mode="duel"]');
    await click('.combat-control-toggle button', 'Tout en IA');
    await click('.combat-choice-launch');
    await page.waitForFunction(() => document.querySelector('[data-auto-dungeon] .fight-heading')?.textContent.includes('Canyon'), { timeout: 120000 });
    await click('.auto-result-button');
    assert.equal(await page.$eval('[data-outcome]', e => e.dataset.outcome), 'victory');
    await click('.fight-heading-actions button', 'Retour à Combat');
    assert.equal(await page.$eval('[data-mode="duel"]', e => e.getAttribute('aria-pressed')), 'true');
    await page.reload({ waitUntil: 'networkidle0' });
    await click('.setup-navigation [aria-label="Combat"]');
    assert.equal(await page.$eval('[data-mode="duel"]', e => e.getAttribute('aria-pressed')), 'true');
    assert.equal(await page.$eval('.combat-control-toggle button:last-child', e => e.getAttribute('aria-pressed')), 'true');
    assert(!await visible('.combat-resume'));
    check('automatic duel also starts from Combat; mode, map and AI settings survive reload');
    assert.deepEqual(report.errors, []);
    fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2));
  } catch (error) {
    report.failure = error.stack;
    await capture('failure').catch(() => {});
    fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2));
    fs.writeFileSync(path.join(out, 'failure.txt'), await page.evaluate(() => document.body.innerText));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
